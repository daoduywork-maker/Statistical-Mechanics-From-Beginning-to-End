"""Write unary-fv-triple.tex: f(v) of a solid, a liquid and a vapor at fixed T.

(a) Triple point: one line touches all three curves.
(b) Below the triple point: the solid curve is lowered by DELTA. The solid--vapor
    tangent forms the convex hull, and the liquid--vapor tangent lies above the
    solid curve (metastable coexistence of liquid and vapor).

Model curves, measured from the triple-point line L(v) = MU0 - P0 v:
    solid  f_s = L + K_S (v - VS)^2
    liquid f_l = L + K_L (v - VL)^2
    vapor  f_g = L + C_G [v/VG - 1 - ln(v/VG)]     (convex, tangent to L at VG)

Usage: python3 make_unary_fv_triple.py > unary-fv-triple.tex   (needs numpy, scipy)
"""
import numpy as np
from scipy.optimize import fsolve

MU0, P0 = 5.0, 0.45
VS, VL, VG = 1.0, 1.7, 5.6
K_S, K_L, C_G = 7.0, 2.4, 8.0
DELTA = 1.0
SX, SY = 0.88, 0.75          # cm per unit
x = lambda v: v * SX
y = lambda f: f * SY


def line(v):
    return MU0 - P0 * v


def f_s(v, d=0.0):
    return line(v) + K_S * (v - VS) ** 2 - d


def f_l(v):
    return line(v) + K_L * (v - VL) ** 2


def f_g(v):
    return line(v) + C_G * (v / VG - 1 - np.log(v / VG))


def df(f, v, h=1e-6):
    return (f(v + h) - f(v - h)) / (2 * h)


def common_tangent(fa, fb, guess):
    def eqs(z):
        a, b = z
        chord = (fb(b) - fa(a)) / (b - a)
        return [df(fa, a) - chord, df(fb, b) - chord]
    return fsolve(eqs, guess, xtol=1e-12)


def path(f, v0, v1, n=80):
    vs = np.linspace(v0, v1, n)
    return " -- ".join(f"({x(v):.3f},{y(f(v)):.3f})" for v in vs)


def seg(v0, f0, v1, f1):
    return f"({x(v0):.3f},{y(f0):.3f}) -- ({x(v1):.3f},{y(f1):.3f})"


S_RANGE, L_RANGE, G_RANGE = (0.6, 1.4), (1.05, 2.5), (3.0, 7.2)
fs_low = lambda v: f_s(v, DELTA)
a, b = common_tangent(fs_low, f_g, [VS, VG])
slope = df(fs_low, a)
print(f"% s-v tangent: v_s={a:.4f}, v_g={b:.4f}, P={-slope:.4f}")


def panel(shift, tag, below):
    out = [rf"\begin{{scope}}[xshift={shift}cm]",
           r"    \draw[->] (0,0) -- (7.0,0) node[right] {$v$};",
           r"    \draw[->] (0,0) -- (0,5.2) node[above] {$f$};",
           rf"    \node[anchor=north west] at (-0.1,-0.35) {{{tag}}};"]
    fs = fs_low if below else f_s
    out += [rf"    \draw {path(fs, *S_RANGE)};",
            rf"    \draw {path(f_l, *L_RANGE)};",
            rf"    \draw {path(f_g, *G_RANGE)};",
            rf"    \node[left] at ({x(S_RANGE[0]) - 0.02:.3f},{y(fs(S_RANGE[0])):.3f}) {{$f_s$}};",
            rf"    \node[above] at ({x(L_RANGE[1]):.3f},{y(f_l(L_RANGE[1])) + 0.02:.3f}) {{$f_l$}};",
            rf"    \node[above] at ({x(G_RANGE[1]):.3f},{y(f_g(G_RANGE[1])) + 0.02:.3f}) {{$f_g$}};"]
    if not below:
        out += [rf"    \draw[line width=1.6pt] {seg(VS, line(VS), VG, line(VG))};"]
        out += [rf"    \fill ({x(v):.3f},{y(line(v)):.3f}) circle (2pt);" for v in (VS, VL, VG)]
        out += [rf"    \node[align=left, right] at ({x(1.6):.3f},{y(line(4.2)) - 0.55:.3f}) "
                r"{one tangent to\\[-2pt]$f_s$, $f_l$ and $f_g$};",
                rf"    \node[above right] at (0.1,5.0) {{$T=T_t$}};"]
    else:
        out += [rf"    \draw[dashed] {seg(VL, line(VL), VG, line(VG))};",
                rf"    \draw[line width=1.6pt] {seg(a, fs_low(a), b, f_g(b))};",
                rf"    \fill ({x(a):.3f},{y(fs_low(a)):.3f}) circle (2pt);",
                rf"    \fill ({x(b):.3f},{y(f_g(b)):.3f}) circle (2pt);",
                rf"    \filldraw[fill=white, line width=0.6pt] ({x(VL):.3f},{y(line(VL)):.3f}) circle (2pt);",
                rf"    \filldraw[fill=white, line width=0.6pt] ({x(VG):.3f},{y(line(VG)):.3f}) circle (2pt);",
                rf"    \node[right] at ({x(4.3):.3f},4.3) {{$l+g$ (metastable)}};",
                rf"    \draw[line width=0.5pt] ({x(4.3) + 0.05:.3f},4.12) -- ({x(3.2):.3f},{y(line(3.2)) + 0.04:.3f});",
                rf"    \node[right] at ({x(1.6):.3f},{y(fs_low(a) + slope * (4.6 - a)) - 0.45:.3f}) {{$s+g$ (convex hull)}};",
                rf"    \node[above right] at (0.1,5.0) {{$T<T_t$}};"]
    out.append(r"\end{scope}")
    return "\n".join(out)


