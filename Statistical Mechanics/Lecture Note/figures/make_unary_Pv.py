"""Write unary-Pv.tex: isotherms in the P--v plane from the van der Waals
equation in reduced units, P = 8T/(3v - 1) - 3/v^2 (critical point at 1, 1, 1).
The coexisting volumes and the saturation pressure follow from the Maxwell
equal-area rule, which is the common tangent of f(v) in the notes.

Usage: python3 make_unary_Pv.py > unary-Pv.tex   (needs numpy, scipy)
"""
import numpy as np
from scipy.optimize import brentq

T_LOW, T_HIGH = 0.85, 1.2          # isotherms below and above Tc
V_MAX, P_MAX = 4.3, 1.6
SX, SY = 1.75, 3.6                # cm per reduced unit
V0 = 0.35                         # room for the liquid label left of the liquid branch
x = lambda v: (v + V0) * SX
y = lambda p: p * SY


def P(v, T):
    return 8 * T / (3 * v - 1) - 3 / v**2


def maxwell(T):
    """Coexisting (v_l, v_g, P_sat) from the equal-area rule.

    For a trial pressure p, the outer roots of 3p v^3 - (p + 8T) v^2 + 9v - 3 = 0
    are the liquid and vapor volumes, and P_sat makes the two areas equal.
    """
    vs = np.linspace(0.34, 60, 200000)
    ps = P(vs, T)
    dp = np.diff(ps)
    i_min = np.argmax(dp > 0)                 # spinodal minimum
    i_max = i_min + np.argmax(dp[i_min:] < 0)  # spinodal maximum
    lo, hi = max(ps[i_min], 1e-9) + 1e-12, ps[i_max] - 1e-12

    def roots(p):
        r = np.roots([3 * p, -(p + 8 * T), 9, -3])
        r = np.sort(r[np.abs(r.imag) < 1e-9].real)
        return r[0], r[-1]

    def area(p):
        vl, vg = roots(p)
        integral = (8 * T / 3) * np.log((3 * vg - 1) / (3 * vl - 1)) + 3 / vg - 3 / vl
        return integral - p * (vg - vl)

    p_sat = brentq(area, lo, hi, xtol=1e-14)
    vl, vg = roots(p_sat)
    return vl, vg, p_sat


def path(points):
    return " -- ".join(f"({x(v):.3f},{y(p):.3f})" for v, p in points)


def branch(T, v0, v1, n=60):
    """Isotherm between v0 and v1, clipped at P_MAX."""
    vs = np.geomspace(v0, v1, n)
    return [(v, P(v, T)) for v in vs if P(v, T) <= P_MAX + 1e-9]


def start_volume(T):
    """Volume at which the isotherm leaves the top of the frame."""
    return brentq(lambda v: P(v, T) - P_MAX, 0.34, 2.0)


vl, vg, ps = maxwell(T_LOW)

# coexistence curve from T = 0.6 up to the critical point
Ts = np.concatenate([np.linspace(0.6, 0.98, 40), [0.99, 0.995, 0.999]])
co = [maxwell(T) for T in Ts]
left = [(a, p) for a, b, p in co]
right = [(b, p) for a, b, p in co if b <= V_MAX]
k = next(i for i, (a, b, p) in enumerate(co) if b <= V_MAX)
(b0, p0), (b1, p1) = (co[k - 1][1], co[k - 1][2]), (co[k][1], co[k][2])
right.insert(0, (V_MAX, p0 + (p1 - p0) * (V_MAX - b0) / (b1 - b0)))
dome = left + [(1.0, 1.0)] + right[::-1]

low_liq = branch(T_LOW, start_volume(T_LOW), vl)
low_vap = branch(T_LOW, vg, V_MAX)
crit = branch(1.0, start_volume(1.0), V_MAX, 120)
high = branch(T_HIGH, start_volume(T_HIGH), V_MAX, 120)
v_mid = vl + 0.35 * (vg - vl)

