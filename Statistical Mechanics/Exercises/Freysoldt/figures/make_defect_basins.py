"""Write defect-basins.tex: the microstates of the crystal grouped into basins.

Each basin is one defect configuration sigma. The ladder in a basin shows the
vibrational states nu of the crystal held in that configuration. The vertical
axis is the exponent of the grand canonical weight,
U - sum_i mu_i N_i - E_F N_e. The offset between the lowest levels of the
perfect crystal and of a crystal with one defect is the formation energy at
T = 0.

The basins are harmonic wells b_k + a_k (x - x_k)^2. The level spacing of a
well scales with sqrt(a_k), so the softer defect wells have closer levels.

Usage: python3 make_defect_basins.py > defect-basins.tex
"""
import math

WELLS = [  # centre x, base b, curvature a, level spacing
    (2.2, 0.60, 1.00, 0.550),
    (5.9, 2.00, 0.60, 0.426),
    (9.6, 2.00, 0.60, 0.426),
]
KAPPA = 3.0        # rounding of the barrier tops (soft minimum)
YTOP = 5.0
NLEV = 4


def landscape(x):
    ys = [b + a * (x - xc) ** 2 for xc, b, a, _ in WELLS]
    m = min(ys)
    return m - math.log(sum(math.exp(-KAPPA * (y - m)) for y in ys)) / KAPPA


xs = [0.0 + i * 0.02 for i in range(int(12.0 / 0.02) + 1)]
pts = [(x, landscape(x)) for x in xs if landscape(x) <= YTOP]

out = [r"""% Standalone figure for "Freysoldt's Review.tex" (Section 4).
% Generated by make_defect_basins.py.
\documentclass[11pt,tikz,border=2pt]{standalone}
\usepackage{amsmath,amssymb}
\usetikzlibrary{arrows.meta, positioning, decorations.pathreplacing}
\begin{document}
\begin{tikzpicture}[font=\small, >=Latex, line width=0.8pt]"""]

# axes
out.append(r"\draw[->] (-0.3,0) -- (12.3,0) node[right, align=left] {atomic\\coordinates};")
out.append(rf"\draw[->] (-0.3,0) -- (-0.3,{YTOP + 0.3:.2f});")
out.append(rf"\node[rotate=90, anchor=south] at (-0.45,{YTOP / 2:.2f}) "
           r"{$U_{\sigma\nu}-\sum_i\mu_iN_{i,\sigma}-E_FN_{e,\sigma}$};")

# landscape
path = " -- ".join(f"({x:.3f},{y:.3f})" for x, y in pts)
out.append(rf"\draw[line width=1.0pt] {path};")

# vibrational levels
ground = []
for xc, b, a, dw in WELLS:
    for nu in range(NLEV):
        e = b + dw * (nu + 0.5)
        hw = math.sqrt((e - b) / a)
        out.append(rf"\draw[line width=0.6pt] ({xc - hw:.3f},{e:.3f}) -- ({xc + hw:.3f},{e:.3f});")
        if nu == 0:
            ground.append((xc, e, hw))

# labels under the wells
labels = [r"$\sigma=0$\\no defect", r"one defect\\at site 1", r"one defect\\at site 2"]
for (xc, _, _, _), lab in zip(WELLS, labels):
    out.append(rf"\node[below, align=center] at ({xc:.2f},-0.05) {{{lab}}};")

# formation energy at T = 0: offset between the lowest levels
(x1, e1, hw1), (x2, e2, hw2) = ground[0], ground[1]
xa = 3.75
out.append(rf"\draw[dotted] ({x1 + hw1:.3f},{e1:.3f}) -- ({xa + 0.15:.3f},{e1:.3f});")
out.append(rf"\draw[dotted] ({x2 - hw2:.3f},{e2:.3f}) -- ({xa - 0.15:.3f},{e2:.3f});")
out.append(rf"\draw[<->, line width=0.6pt] ({xa:.3f},{e1:.3f}) -- ({xa:.3f},{e2:.3f});")
out.append(rf"\node[right] at ({xa + 0.02:.3f},{(e1 + e2) / 2 - 0.05:.3f}) {{$E^f$ at $T=0$}};")

# barrier
xb = (WELLS[1][0] + WELLS[2][0]) / 2
out.append(rf"\node[above] at ({xb:.2f},{landscape(xb) + 0.05:.3f}) {{barrier $\gg k_BT$}};")

# brace: vibrational states of one configuration
xc, b, a, dw = WELLS[2]
e_lo, e_hi = b + dw * 0.5, b + dw * (NLEV - 0.5)
xbr = 11.45
out.append(rf"\draw[decorate, decoration={{brace, mirror, amplitude=4pt}}, line width=0.6pt] "
           rf"({xbr:.2f},{e_lo:.3f}) -- ({xbr:.2f},{e_hi:.3f});")
out.append(rf"\node[right, align=left] at ({xbr + 0.15:.2f},{(e_lo + e_hi) / 2:.3f}) "
           r"{vibrational\\states $\nu$};")

# brace: configurations with one defect
out.append(r"\draw[decorate, decoration={brace, mirror, amplitude=5pt}, line width=0.6pt] "
           rf"({WELLS[1][0] - 1.2:.2f},-1.05) -- ({WELLS[2][0] + 1.2:.2f},-1.05);")
out.append(rf"\node[below] at ({xb:.2f},-1.25) "
           r"{configurations $\sigma$ with $N_X(\sigma)=1$, equal $\Phi_\sigma$};")

out.append(r"""\end{tikzpicture}
\end{document}""")
print("\n".join(out))
