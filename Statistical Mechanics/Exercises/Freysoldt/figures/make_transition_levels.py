"""Write transition-levels.tex: formation energy against the Fermi level for
three model defects, with the lower envelope (the stable charge state) in red.

(a) charge states +1, 0, -1 with U > 0: the neutral state has a window.
(b) charge states +1, 0, -1 with U < 0: the neutral state is never stable.
(c) charge states +2, +1, 0, -1: the state +1 is skipped (negative U), and
    the windows of the remaining states have different widths.

E^f[X^q] = E0[q] + q E_F, with E_F from the valence-band maximum (VBM) to
the conduction-band minimum (CBM) at the band gap EG. All energies in eV.

Usage: python3 make_transition_levels.py > transition-levels.tex
"""
EG = 2.0
PANELS = [
    ("(a) $U>0$", {+1: 0.3, 0: 1.3, -1: 2.9}),
    ("(b) $U<0$", {+1: 0.3, 0: 1.6, -1: 2.3}),
    ("(c) four charge states", {+2: 0.0, +1: 0.9, 0: 1.6, -1: 3.0}),
]
W, H, YMAX = 3.7, 3.6, 3.0
LAB = {2: "+2", 1: "+1", 0: "0", -1: "-1"}


def envelope(E0):
    """Breakpoints of min_q (E0[q] + q x) on [0, EG]."""
    xs = [i * EG / 4000 for i in range(4001)]
    best = [min(E0, key=lambda q: (E0[q] + q * x, -q)) for x in xs]
    pts, segs = [(0.0, min(E0[q] for q in [best[0]]))], []
    start, cur = 0.0, best[0]
    for x, q in zip(xs, best):
        if q != cur:
            # exact crossing of the two lines
            xc = (E0[q] - E0[cur]) / (cur - q)
            segs.append((cur, start, xc)); start, cur = xc, q
    segs.append((cur, start, EG))
    return segs


def panel(shift, title, E0):
    px = lambda x: x / EG * W
    py = lambda y: y / YMAX * H
    out = [rf"\begin{{scope}}[xshift={shift}cm]",
           rf"\draw[->] (0,0) -- ({W + 0.3:.2f},0) node[right] {{$E_F$}};",
           rf"\draw[->] (0,0) -- (0,{H + 0.3:.2f}) node[above] {{$E^f$}};",
           rf"\draw ({W:.3f},0) -- ({W:.3f},{H:.3f});",
           r"\node[below] at (0,0) {VBM};",
           rf"\node[below] at ({W:.3f},0) {{CBM}};",
           rf"\node[anchor=south] at ({W / 2 + 0.3:.3f},{H + 0.75:.2f}) {{{title}}};",
           rf"\begin{{scope}}\clip (0,0) rectangle ({W:.3f},{H:.3f});"]
    for q, e in E0.items():
        out.append(rf"\draw[line width=0.6pt] ({px(0):.3f},{py(e):.3f}) -- ({px(EG):.3f},{py(e + q * EG):.3f});")
    segs = envelope(E0)
    path = " -- ".join([f"({px(segs[0][1]):.3f},{py(E0[segs[0][0]] + segs[0][0] * segs[0][1]):.3f})"] +
                       [f"({px(b):.3f},{py(E0[q] + q * b):.3f})" for q, a, b in segs])
    out.append(rf"\draw[red, line width=2.0pt] {path};")
    out.append(r"\end{scope}")
    # line labels at the right edge (or at the top edge if the line leaves the frame)
    for q, e in E0.items():
        yR = e + q * EG
        if 0 <= yR <= YMAX:
            out.append(rf"\node[right, font=\footnotesize] at ({W:.3f},{py(yR):.3f}) {{${LAB[q]}$}};")
        else:
            xT = (YMAX - e) / q
            out.append(rf"\node[above, font=\footnotesize] at ({px(xT):.3f},{H:.3f}) {{${LAB[q]}$}};")
    # transition levels on the envelope
    for k, ((q1, a, b), (q2, _, _)) in enumerate(zip(segs, segs[1:])):
        y = E0[q1] + q1 * b
        out.append(rf"\draw[dotted] ({px(b):.3f},0) -- ({px(b):.3f},{py(y):.3f});")
        out.append(rf"\fill ({px(b):.3f},{py(y):.3f}) circle (1.8pt);")
        lab = rf"\varepsilon({LAB[q1]}/{LAB[q2]})"
        out.append(rf"\node[below, font=\footnotesize] at ({px(b):.3f},{-0.42 - 0.4 * k:.2f}) {{${lab}$}};")
    # U markers for the +1/0/-1 panels
    if set(E0) == {1, 0, -1}:
        e1 = E0[0] - E0[1]          # eps(+1/0)
        e2 = E0[-1] - E0[0]         # eps(0/-1)
        yU = 0.35
        out.append(rf"\draw[<->, line width=0.6pt] ({px(e1):.3f},{yU:.3f}) -- ({px(e2):.3f},{yU:.3f});")
        mid = px((e1 + e2) / 2)
        lab = "U" if e2 > e1 else r"|U|"
        out.append(rf"\node[above, font=\footnotesize] at ({mid:.3f},{yU:.3f}) {{${lab}$}};")
        if e2 < e1:  # mark the two (unstable) crossings with the neutral line
            for x in (e1, e2):
                out.append(rf"\draw[dotted] ({px(x):.3f},0) -- ({px(x):.3f},{py(E0[0]):.3f});")
                out.append(rf"\draw[line width=0.6pt, fill=white] ({px(x):.3f},{py(E0[0]):.3f}) circle (1.8pt);")
    out.append(r"\end{scope}")
    return "\n".join(out)


print(r"""% Standalone figure for freysoldt.tex (Section 2).
% Generated by make_transition_levels.py.
\documentclass[11pt,tikz,border=2pt]{standalone}
\usepackage{amsmath,amssymb}
\usetikzlibrary{arrows.meta, positioning}
\begin{document}
\begin{tikzpicture}[font=\small, >=Latex, line width=0.8pt]""")
for k, (t, E0) in enumerate(PANELS):
    print(panel(k * 5.45, t, E0))
print(r"""\end{tikzpicture}
\end{document}""")
