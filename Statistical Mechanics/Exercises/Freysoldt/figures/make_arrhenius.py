"""Write arrhenius.tex: Gibbs energy of vacancy formation in Al and the
Arrhenius plot, from a model built to reproduce the GGA values (with
anharmonicity) of Table I of Freysoldt et al., Rev. Mod. Phys. 86, 253 (2014).

Model: the formation entropy rises smoothly from its quantum limit S = 0 at
T = 0 to S_inf at high temperature,
    S_f(T) = S_inf [1 - exp(-(T/T1)^2)],
so that
    G_f(T) = H0 - S_inf [T - (sqrt(pi)/2) T1 erf(T/T1)].
H0 = 0.63 eV is the 0 K value. S_inf = 1.5 k_B and T1 are chosen so that the
tangent at T_m has the intercept 0.68 eV and the slope -1.5 k_B (Table I).
The experimental line uses H = 0.76 eV and S = 2.4 k_B (Table I).

Usage: python3 make_arrhenius.py > arrhenius.tex   (needs numpy, scipy)
"""
import numpy as np
from scipy.special import erf

KB = 8.617333e-5          # eV/K
TM = 933.0
H0, S_INF, H_TM = 0.63, 1.5 * KB, 0.68
T1 = (H_TM - H0) / (S_INF * np.sqrt(np.pi) / 2)   # intercept of the high-T asymptote
H_EXP, S_EXP = 0.76, 2.4 * KB


def G(T):
    return H0 - S_INF * (T - np.sqrt(np.pi) / 2 * T1 * erf(T / T1))


def S(T):
    return S_INF * (1 - np.exp(-(T / T1) ** 2))


H_tan = G(TM) + TM * S(TM)          # intercept of the tangent at T_m
S_tan = S(TM)

# ---------------------------------------------------------------- panel (a)
W, H = 5.6, 4.6
TMAX, GLO, GHI = 1000.0, 0.53, 0.72
ax = lambda T: T / TMAX * W
ay = lambda g: (g - GLO) / (GHI - GLO) * H
Ts = np.linspace(0, TMAX, 200)
curve = " -- ".join(f"({ax(t):.3f},{ay(G(t)):.3f})" for t in Ts)
tan = lambda t: H_tan - S_tan * t

out = [r"""% Standalone figure for freysoldt.tex (Exercise 4).
% Generated by make_arrhenius.py.
\documentclass[11pt,tikz,border=2pt]{standalone}
\usepackage{amsmath,amssymb}
\usetikzlibrary{arrows.meta, positioning}
\begin{document}
\begin{tikzpicture}[font=\small, >=Latex, line width=0.8pt]"""]
out.append(r"\begin{scope}")
for t in range(0, 1001, 200):
    out.append(rf"\draw ({ax(t):.3f},0) -- ({ax(t):.3f},-0.08) node[below] {{{t}}};")
for g in (0.55, 0.60, 0.65, 0.70):
    out.append(rf"\draw (0,{ay(g):.3f}) -- (-0.08,{ay(g):.3f}) node[left] {{{g:.2f}}};")
out += [rf"\draw[->] (0,0) -- ({W + 0.3:.2f},0) node[right] {{$T$ (K)}};",
        rf"\draw[->] (0,0) -- (0,{H + 0.3:.2f}) node[above] {{$G^f$ (eV)}};",
        rf"\fill[gray!15] ({ax(0.55 * TM):.3f},0) rectangle ({ax(TM):.3f},{H:.3f});",
        rf"\node[align=center, font=\footnotesize] at ({ax(0.775 * TM):.3f},{ay(0.555):.3f}) {{measured\\[-2pt]range}};",
        rf"\draw[dashed] (0,{ay(H0):.3f}) -- ({W:.3f},{ay(H0):.3f});",
        rf"\node[above left] at ({W:.3f},{ay(H0):.3f}) {{$H^f(0)=0.63$~eV}};",
        rf"\draw[dotted, line width=1.0pt] (0,{ay(tan(0)):.3f}) -- ({ax(TMAX):.3f},{ay(tan(TMAX)):.3f});",
        rf"\fill (0,{ay(H_tan):.3f}) circle (2pt);",
        rf"\node[above right] at (0.05,{ay(H_tan):.3f}) {{$H^f(T^m)={H_tan:.2f}$~eV}};",
        rf"\draw[line width=1.4pt] {curve};",
        rf"\fill ({ax(TM):.3f},{ay(G(TM)):.3f}) circle (2pt);",
        rf"\draw[dotted] ({ax(TM):.3f},0) -- ({ax(TM):.3f},{ay(G(TM)):.3f});",
        rf"\node[below] at ({ax(TM):.3f},-0.45) {{$T^m$}};",
        rf"\node[anchor=north east] at ({ax(330):.3f},{ay(0.615):.3f}) {{$G^f(T)$}};",
        rf"\node[anchor=north west] at (-0.1,-0.85) {{(a)}};",
        r"\end{scope}"]

# ---------------------------------------------------------------- panel (b)
X0 = 8.2
R0, R1 = 1.0, 3.0              # T_m/T range
L0, L1 = -12.0, -2.0           # log10 c range
bx = lambda r: X0 + (r - R0) / (R1 - R0) * W
by = lambda l: (l - L0) / (L1 - L0) * H
rs = np.linspace(R0, R1, 120)
log_true = lambda r: -G(TM / r) / (KB * TM / r) / np.log(10)
log_exp = lambda r: (S_EXP / KB - H_EXP / (KB * TM / r)) / np.log(10)
log_0K = lambda r: -H0 / (KB * TM / r) / np.log(10)
path = lambda f: " -- ".join(f"({bx(r):.3f},{by(f(r)):.3f})" for r in rs if L0 <= f(r) <= L1)
out.append(r"\begin{scope}")
for r in (1.0, 1.5, 2.0, 2.5, 3.0):
    out.append(rf"\draw ({bx(r):.3f},0) -- ({bx(r):.3f},-0.08) node[below] {{{r:.1f}}};")
for l in range(-12, -1, 2):
    out.append(rf"\draw ({X0:.3f},{by(l):.3f}) -- ({X0 - 0.08:.3f},{by(l):.3f}) node[left] {{$10^{{{l}}}$}};")
out += [rf"\fill[gray!15] ({bx(1.0):.3f},0) rectangle ({bx(1 / 0.55):.3f},{H:.3f});",
        rf"\draw[->] ({X0:.3f},0) -- ({X0 + W + 0.3:.2f},0) node[right] {{$T^m/T$}};",
        rf"\draw[->] ({X0:.3f},0) -- ({X0:.3f},{H + 0.3:.2f}) node[above] {{$c^{{\text{{eq}}}}$}};",
        rf"\draw[line width=1.4pt] {path(log_true)};",
        rf"\draw[dash dot, line width=1.0pt] {path(log_exp)};",
        rf"\draw[dashed] {path(log_0K)};",
        rf"\node[anchor=north west] at ({X0 - 0.1:.3f},-0.85) {{(b)}};"]
# legend
lx, ly = bx(1.85), by(-2.6)
out += [rf"\draw[line width=1.4pt] ({lx:.3f},{ly:.3f}) -- ({lx + 0.6:.3f},{ly:.3f}) node[right] {{model, $G^f(T)$}};",
        rf"\draw[dash dot, line width=1.0pt] ({lx:.3f},{ly - 0.45:.3f}) -- ({lx + 0.6:.3f},{ly - 0.45:.3f}) node[right] {{experiment, Table~I}};",
        rf"\draw[dashed] ({lx:.3f},{ly - 0.9:.3f}) -- ({lx + 0.6:.3f},{ly - 0.9:.3f}) node[right] {{$H^f(0)$, $S^f=0$}};",
        r"\end{scope}"]
out.append(r"""\end{tikzpicture}
\end{document}""")
print("\n".join(out))
print(f"% check: H_tan = {H_tan:.4f} eV, S_tan = {S_tan / KB:.3f} k_B, T1 = {T1:.1f} K")
