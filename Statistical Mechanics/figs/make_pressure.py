"""P-T projection and isobaric T-X sections of an isomorphous binary system
with solid (alpha), liquid (L) and gas (G) solutions.

Model (k_B = 1, pure solid as reference):
  liquid:  mu_i^l - mu_i^s = s_f (T_i - T)
  gas:     mu_i^g - mu_i^s = s_f (T_i - T) + l_v (1 - T/T_b,i) + T ln P
All three phases are ideal solutions.  Run:
  python3 make_pressure.py > binary_pressure.tex
"""
import sys
import numpy as np
from hull_pd import solution
from make_gallery import region_map, boundaries, dedupe, labels

SF, LV = 1.2, 10.0
T1, T2, TB1, TB2 = 1.0, 1.4, 1.8, 2.4
PRESSURES = [("p_1", 1.0), ("p_2", 0.042), ("p_3", 0.006)]
zero = lambda T: 0.0


def phases(P):
    sol = solution(zero, zero, 0.0)
    liq = solution(lambda T: SF * (T1 - T), lambda T: SF * (T2 - T), 0.0)
    gas = solution(lambda T: SF * (T1 - T) + LV * (1 - T / TB1) + T * np.log(P),
                   lambda T: SF * (T2 - T) + LV * (1 - T / TB2) + T * np.log(P), 0.0)
    return [sol, liq, gas]


def lnP_sub(T, Ti, Tb):
    return -(SF * (Ti - T) + LV * (1 - T / Tb)) / T


def lnP_vap(T, Tb):
    return -LV * (1 - T / Tb) / T


def three_phase_T(P):
    """Temperature of the binary G + L + alpha equilibrium at pressure P."""
    from hull_pd import diagram
    _, three = diagram(phases(P), np.linspace(T1 + 0.001, T2 - 0.001, 241))
    return three[0][0] if three else None


# P-T panel coordinates
TX0, TX1 = 0.85, 2.2
LY0, LY1 = -2.5, 0.35
PW, PH = 5.6, 5.0


def pt(T, lnP):
    return ((T - TX0) / (TX1 - TX0) * PW, (lnP / np.log(10) - LY0) / (LY1 - LY0) * PH)


def path(pts):
    return " -- ".join(f"({x:.3f},{y:.3f})" for x, y in pts)


def main():
    out = sys.stdout
    out.write("% Generated by make_pressure.py -- do not edit by hand.\n")
    # ---------------- P-T projection ----------------
    out.write("\\begin{scope}\n")
    out.write(f"  \\draw[->] (0,0) -- ({PW + 0.3},0) node[right] {{$T$}};\n")
    out.write(f"  \\draw[->] (0,0) -- (0,{PH + 0.3}) node[above] {{$\\ln P$}};\n")
    for name, Ti, Tb in (("A", T1, TB1), ("B", T2, TB2)):
        lnPt = lnP_sub(Ti, Ti, Tb)
        Tsub = np.linspace(TX0, Ti, 40)
        sub = [pt(T, lnP_sub(T, Ti, Tb)) for T in Tsub if lnP_sub(T, Ti, Tb) / np.log(10) > LY0]
        Tvap = np.linspace(Ti, TX1, 60)
        vap = [pt(T, lnP_vap(T, Tb)) for T in Tvap if lnP_vap(T, Tb) / np.log(10) < LY1]
        out.write(f"  \\draw {path(sub)};\n")
        out.write(f"  \\draw {path(vap)};\n")
        x0, y0 = pt(Ti, lnPt)
        out.write(f"  \\draw ({x0:.3f},{y0:.3f}) -- ({x0:.3f},{PH:.3f});\n")
        out.write(f"  \\fill ({x0:.3f},{y0:.3f}) circle (1.5pt);\n")
        out.write(f"  \\node[font=\\scriptsize, below right] at ({x0:.3f},{y0:.3f}) {{$O_{name}$}};\n")
        xs_, ys_ = sub[int(len(sub) * 0.45)]
        out.write(f"  \\node[font=\\tiny, right] at ({xs_:.3f},{ys_:.3f}) {{$G\\alpha_{name}$}};\n")
        xv_, yv_ = vap[-1]
        out.write(f"  \\node[font=\\tiny, right] at ({xv_:.3f},{yv_:.3f}) {{$GL_{name}$}};\n")
        out.write(f"  \\node[font=\\tiny, right] at ({x0:.3f},{PH - 0.25:.3f}) {{$L\\alpha_{name}$}};\n")
    # binary three-phase curve G + L + alpha between the triple points
    lnPa, lnPb = lnP_sub(T1, T1, TB1), lnP_sub(T2, T2, TB2)
    u = 0.5 - 0.5 * np.cos(np.linspace(0, np.pi, 34))
    Ps = np.exp(lnPa + (lnPb - lnPa) * u)[1:-1]
    inner = [(three_phase_T(P), P) for P in Ps]
    curve = [pt(T1, lnPa)] + [pt(T, np.log(P)) for T, P in inner if T] + [pt(T2, lnPb)]
    out.write(f"  \\draw[line width=1.2pt] {path(curve)};\n")
    xm, ym = curve[len(curve) // 2]
    out.write(f"  \\node[font=\\tiny, above left] at ({xm:.3f},{ym:.3f}) {{$GL\\alpha$}};\n")
    # isobars
    for name, P in PRESSURES:
        y = pt(TX0, np.log(P))[1]
        out.write(f"  \\draw[dashed, line width=0.4pt] (0,{y:.3f}) -- ({PW},{y:.3f}) "
                  f"node[right, font=\\scriptsize] {{${name}$}};\n")
    out.write(f"  \\node[font=\\scriptsize, below] at ({PW/2},-0.35) {{(a) $P$--$T$ projection}};\n")
    out.write("\\end{scope}\n")
    # ---------------- T-X sections ----------------
    import make_gallery as mg
    mg.W, mg.H = 2.6, 2.3
    ranges = {"p_1": (0.85, 2.55), "p_2": (0.95, 1.42), "p_3": (0.88, 1.16)}

    def names(p, x, k=0):
        return [r"\alpha", "L", "G"][p]

    for j, (name, P) in enumerate(PRESSURES):
        t0, t1 = ranges[name]
        Ts = np.linspace(t0, t1, 241)
        code, pairs = region_map(phases(P), Ts)
        lines = dedupe(boundaries(code, Ts))
        ox = PW + 1.3 + (j % 2) * (mg.W + 0.6)
        oy = 2.9 - (j // 2) * (mg.H + 0.9)
        out.write(f"\\begin{{scope}}[shift={{({ox:.2f},{oy:.2f})}}]\n")
        out.write(f"  \\draw[line width=0.5pt] (0,0) rectangle ({mg.W},{mg.H});\n")
        for ln in lines:
            out.write(f"  \\draw {path(ln)};\n")
        for (x, y, text, size) in labels(code, pairs, Ts, names):
            out.write(f"  \\node[font=\\tiny, fill=white, inner sep=0.5pt] at ({x:.2f},{y:.2f}) {{${text}$}};\n")
        letter = "bcd"[j]
        out.write(f"  \\node[font=\\scriptsize, below] at ({mg.W/2},-0.05) {{({letter}) $T$--$X$ at ${name}$}};\n")
        out.write("\\end{scope}\n")


if __name__ == "__main__":
    main()
